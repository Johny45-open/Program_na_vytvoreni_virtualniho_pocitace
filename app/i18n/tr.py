_STRINGS = {"cs": _CS, "en": _EN}


class LangManager(QObject):
    changed = Signal(str)

    def __init__(self, lang="cs"):
        super().__init__()
        self.lang = lang if lang in _STRINGS else "cs"

    def set_language(self, lang):
        if lang in _STRINGS and lang != self.lang:
            self.lang = lang
            self.changed.emit(lang)

    def tr(self, key):
        return _STRINGS[self.lang].get(key, _CS.get(key, key))


lang_manager = LangManager()


def tr(key):
    return lang_manager.tr(key)